import {
  AllowNull, BelongsTo, Column, DataType, Default, ForeignKey, HasMany, Model, Table, Unique,
} from 'sequelize-typescript';
import { User } from '../../users/models/user.model';
import { Payment } from '../../payments/models/payment.model';
import { Attachment } from '../../attachments/models/attachment.model';
import { Tracker } from '../../trackers/models/tracker.model';
import { TrackerSchedule } from '../../trackers/models/tracker-schedule.model';
import { ExpenseHistory } from './expense-history.model';
import { ExpenseApproval } from './expense-approval.model';
import { ExpenseStatus } from '../expense-workflow';

@Table({ tableName: 'expenses' })
export class Expense extends Model {
  @Column({ type: DataType.INTEGER.UNSIGNED, autoIncrement: true, primaryKey: true })
  id!: number;

  @ForeignKey(() => User)
  @AllowNull(false)
  @Column(DataType.INTEGER.UNSIGNED)
  employeeId!: number;

  @BelongsTo(() => User, 'employeeId')
  employee!: User;

  @ForeignKey(() => Tracker)
  @Column(DataType.INTEGER.UNSIGNED)
  trackerId!: number | null;

  @BelongsTo(() => Tracker)
  tracker!: Tracker;

  // Set only for expenses generated by a recurring schedule
  @ForeignKey(() => TrackerSchedule)
  @Unique({ name: 'uq_schedule_occurrence', msg: 'This occurrence was already generated' })
  @Column(DataType.INTEGER.UNSIGNED)
  scheduleId!: number | null;

  @Unique({ name: 'uq_schedule_occurrence', msg: 'This occurrence was already generated' })
  @Column(DataType.DATEONLY)
  occurrenceDate!: string | null;

  @AllowNull(false)
  @Column(DataType.STRING(60))
  category!: string;

  // DECIMAL comes back from MySQL as a string; services convert with Number()
  @AllowNull(false)
  @Column(DataType.DECIMAL(12, 2))
  amount!: number;

  @Default('INR')
  @Column(DataType.STRING(3))
  currency!: string;

  @AllowNull(false)
  @Column(DataType.DATEONLY)
  expenseDate!: string;

  @Column(DataType.STRING(500))
  description!: string;

  @Default(ExpenseStatus.DRAFT)
  @Column(DataType.ENUM(...Object.values(ExpenseStatus)))
  status!: ExpenseStatus;

  @Default(0)
  @Column(DataType.DECIMAL(12, 2))
  paidAmount!: number;

  @Column(DataType.DATE)
  submittedAt!: Date;

  @Column(DataType.INTEGER.UNSIGNED)
  approvedById!: number;

  @Column(DataType.DATE)
  approvedAt!: Date;

  @Column(DataType.STRING(500))
  rejectionReason!: string;

  @HasMany(() => ExpenseApproval)
  approvals!: ExpenseApproval[];

  @HasMany(() => Payment)
  payments!: Payment[];

  @HasMany(() => ExpenseHistory)
  history!: ExpenseHistory[];

  @HasMany(() => Attachment)
  attachments!: Attachment[];
}
